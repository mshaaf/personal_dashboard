#!/usr/bin/env node
// Generates supabase/exercises_seed.sql from the free-exercise-db dataset.
// Usage: node scripts/gen-exercises-seed.mjs
// The generated SQL inserts ~870 exercises as GLOBAL entries (user_id = NULL,
// source = 'free-exercise-db'). Paste it into the Supabase SQL editor (it runs
// as admin, so the NULL user_id rows bypass RLS). Re-running is safe.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const SRC = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json'
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', 'exercises_seed.sql')

// Postgres single-quote escape
const q = (v) => (v == null ? null : `'${String(v).replace(/'/g, "''")}'`)
// text[] literal, or NULL
const arr = (a) => {
  if (!Array.isArray(a) || a.length === 0) return "'{}'::text[]"
  return `array[${a.map((x) => q(x)).join(',')}]::text[]`
}

const res = await fetch(SRC)
if (!res.ok) throw new Error(`Fetch failed: ${res.status}`)
const exercises = await res.json()

const rows = exercises.map((e) => {
  const name = q(e.name) ?? "''"
  const category = q(e.category) // e.g. strength, stretching, cardio
  const equipment = q(e.equipment)
  const primary = arr(e.primaryMuscles)
  const secondary = arr(e.secondaryMuscles)
  const instructions = arr(e.instructions)
  return `(${name}, ${category}, ${equipment}, ${primary}, ${secondary}, ${instructions}, 'free-exercise-db', false)`
})

const sql = `-- ============================================
-- SEED: free-exercise-db (~${exercises.length} global exercises)
-- Generated by scripts/gen-exercises-seed.mjs
-- Run AFTER schema.sql (and optionally seed.sql).
-- Paste into the Supabase SQL editor — runs as admin so the NULL user_id
-- (global) rows insert despite row-level security. Safe to re-run.
-- ============================================

insert into exercises (name, category, equipment, primary_muscles, secondary_muscles, instructions, source, is_favorite) values
${rows.join(',\n')}
on conflict do nothing;
`

writeFileSync(OUT, sql)
console.log(`Wrote ${rows.length} exercises to ${OUT}`)
